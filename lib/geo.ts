// Lightweight stylised world geometry for the custom SVG map components.
// Coordinates are [lon, lat] pairs forming simplified landmass outlines —
// intentionally low-poly for a restrained, terminal-style cartography.
// Inland seas are drawn as overlay shapes on top of the landmasses.

export type LonLat = [number, number];

export const WORLD_WINDOW = { lonMin: -170, lonMax: 180, latMin: -56, latMax: 78 };

export function project(
  lon: number,
  lat: number,
  width: number,
  height: number,
  window = WORLD_WINDOW
): { x: number; y: number } {
  const x = ((lon - window.lonMin) / (window.lonMax - window.lonMin)) * width;
  const y = ((window.latMax - lat) / (window.latMax - window.latMin)) * height;
  return { x, y };
}

export function toPath(
  points: LonLat[],
  width: number,
  height: number,
  window = WORLD_WINDOW
): string {
  return (
    points
      .map(([lon, lat], i) => {
        const { x, y } = project(lon, lat, width, height, window);
        return `${i === 0 ? "M" : "L"}${x.toFixed(1)},${y.toFixed(1)}`;
      })
      .join("") + "Z"
  );
}

